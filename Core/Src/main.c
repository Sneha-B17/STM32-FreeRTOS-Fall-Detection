void Watcher(void *arg){
	for(;;){
		MPU6050_Read();
		//printf("Ax=%d:Ay=%d:Az=%d | Gx=%d:Gy:%d:Gz=%d\r\n",Ax,Ay,Az,Gx,Gy,Gz);
		vTaskDelay(pdMS_TO_TICKS(20));
	}
}

void Thinker(void *arg) {
	for (;;) {
		// 1. Calculate Resultant Acceleration Magnitude
		float aTotal = sqrtf((float) Ax * Ax + (float) Ay * Ay + (float) Az * Az) / ACCEL_SCALE;

		// 2. Only check for Tilt IF an Impact (Threshold) is detected first
		if (aTotal > THRESHOLD) {

			// Add a very tiny delay to let the sensor stabilize after impact
			vTaskDelay(pdMS_TO_TICKS(10));

			float pitch = atan2f(Ax, sqrtf(Ay * Ay + Az * Az)) * 180.0f / M_PI;
			float roll = atan2f(Ay, sqrtf(Ax * Ax + Az * Az)) * 180.0f / M_PI;

			// 3. Confirm the device is actually tilted AFTER the impact
			if (fabs(pitch) > TILT_ANGLE || fabs(roll) > TILT_ANGLE) {
				//uint8_t alert = 1;
				xTaskNotifyGive(shouter);
				vTaskDelay(pdMS_TO_TICKS(2000));
			}
		}
		else{
			BSP_LCD_DisplayStringAt(0, 55, (uint8_t*)"NO...!", CENTER_MODE);
		}
//		vTaskDelay(pdMS_TO_TICKS(50));
	}
}

void Shouter(void *arg){
	for(;;){
		ulTaskNotifyTake(pdTRUE, portMAX_DELAY);
		BSP_LCD_DisplayStringAt(0, 55, (uint8_t*)"YES..!", CENTER_MODE);
		HAL_GPIO_WritePin(GPIOG, GPIO_PIN_14, 1);
		vTaskDelay(pdMS_TO_TICKS(3000));
		HAL_GPIO_WritePin(GPIOG, GPIO_PIN_14, 0);
	}
}
